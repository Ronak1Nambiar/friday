// The second brain, shared by every agent. One protocol file is rendered into the
// form each CLI reads; tool-using agents get read access to the vault through
// their own flags; Ollama (no tools) gets the relevant notes retrieved for it.
// Writes never come straight from agents: they propose them in fenced blocks and
// FRIDAY applies them one at a time through a single queue (pull, write, commit, push).
import { execFile, execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { userName, userPossessive } from './user.js';

export const PROTOCOL_FILE = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'context', 'VAULT_PROTOCOL.md');
// How Ollama (no file tools) writes: proposed ops that FRIDAY applies.
export const OPS_FILE = path.join(path.dirname(PROTOCOL_FILE), 'VAULT_OPS.md');

// Notes keep their own line endings: ~130 of the user's are CRLF. Edits work on LF text
// and write back in the file's own style.
const eolOf = (raw) => (raw.includes('\r\n') ? '\r\n' : '\n');
const toLf = (raw) => raw.replace(/\r\n/g, '\n');
const withEol = (text, eol) => (eol === '\n' ? text : text.replace(/\r?\n/g, eol));

export function renderProtocol(vault, file = PROTOCOL_FILE) {
  let text = '';
  try { text = fs.readFileSync(file, 'utf8'); } catch { return ''; }
  return text.replaceAll('{{vault}}', vault).replaceAll("{{user's}}", userPossessive()).replaceAll('{{user}}', userName());
}

// The same rules under each CLI's own file name, in FRIDAY's config folder (never
// in the user's repos). Returns the paths.
// `sealed`: project names nothing may be read about (profile.private.sealed).
export function writeAgentContext(configDir, vault, { sealed = [] } = {}) {
  const dir = path.join(configDir, 'context');
  let body = renderProtocol(vault);
  if (body && sealed.length) {
    body += `\n## Sealed projects\n\n${sealed.map((s) => s.toUpperCase()).join(', ')} ${sealed.length > 1 ? 'are' : 'is'} sealed: nothing about ${sealed.length > 1 ? 'them' : 'it'} may leave this machine. `
      + 'Do not open, list, search, quote or summarize its folder, its files, or vault notes about it, by any tool or shell command, '
      + "even if a path or search result leads there. If a task needs it, stop and say it must be done with FRIDAY's local model.\n";
  }
  const files = {};
  if (!body) return files;
  fs.mkdirSync(dir, { recursive: true });
  for (const name of ['CLAUDE.md', 'AGENTS.md', 'GEMINI.md']) {
    const f = path.join(dir, name);
    const text = `<!-- Generated by FRIDAY from context/VAULT_PROTOCOL.md. Edit that file, not this one. -->\n${body}`;
    let old = null;
    try { old = fs.readFileSync(f, 'utf8'); } catch {}
    if (old !== text) fs.writeFileSync(f, text);
    files[name] = f;
  }
  return files;
}

// How each agent gets the protocol and read/write access to the vault. Agents edit
// notes directly, as the user's own Claude Code does; FRIDAY commits what they changed.
// Flags checked against
// each CLI's --help:
// - Claude Code: --add-dir <vault>, --append-system-prompt-file CLAUDE.md.
// - Codex: its sandbox reads the whole disk; the vault is added to its writable roots
//   by config (`exec resume` has no --add-dir). Rules go in as developer_instructions.
// - Gemini CLI: --include-directories <vault>; no per-run instructions flag, so
//   GEMINI.md goes in the first message of each session.
// - opencode: OPENCODE_CONFIG_CONTENT adds AGENTS.md as instructions and allows
//   work outside the project in the vault.
// - Ollama (no tools): the protocol, retrieved notes and the ops of VAULT_OPS.md.
// A Claude Code permission glob for everything under an absolute folder. `//` marks
// an absolute path; on Windows Claude Code matches POSIX form, so C:\x is //c/x.
export function denyGlob(dir) {
  const abs = path.resolve(dir).replace(/\\/g, '/').replace(/^([A-Za-z]):/, (_, d) => `/${d.toLowerCase()}`);
  return `/${abs}/**`;
}

export function vaultAccess(agentId, { vault, files }) {
  if (!vault || !files?.['CLAUDE.md']) return { args: [], env: {}, firstTurn: '' };
  const abs = path.resolve(vault);
  switch (agentId) {
    case 'claude':
      return { args: ['--add-dir', abs, '--append-system-prompt-file', files['CLAUDE.md']], env: {}, firstTurn: '' };
    case 'codex':
      return { args: ['-c', `developer_instructions=${JSON.stringify(fs.readFileSync(files['AGENTS.md'], 'utf8'))}`,
        '-c', `sandbox_workspace_write.writable_roots=[${JSON.stringify(abs)}]`], env: {}, firstTurn: '' };
    case 'gemini':
      return { args: ['--include-directories', abs], env: {}, firstTurn: fs.readFileSync(files['GEMINI.md'], 'utf8') };
    case 'opencode':
      return { args: [], env: { OPENCODE_CONFIG_CONTENT: JSON.stringify({
        instructions: [files['AGENTS.md']],
        permission: { external_directory: { [`${abs}/**`]: 'allow' } },
      }) }, firstTurn: '' };
    default:
      return { args: [], env: {}, firstTurn: '' };
  }
}

// ---- retrieval ---------------------------------------------------------------
const STOP = new Set(('the a an and or but of to in on for with about from into by at is are was were be been do did does done '
  + 'what whats which who whom how why when where this that these those it its i me my mine you your we our they them '
  + 'can could should would will shall may might must have has had not no yes so if then than too very just also '
  + 'project projects note notes thing things stuff next now tell give show please make get let decide decided '
  + 'summarize summary write help need want know any some all more most much many one two new old').split(' '));

export function queryTokens(text) {
  return [...new Set(text.toLowerCase().split(/[^a-z0-9]+/).filter((w) => w.length >= 3 && !STOP.has(w))
    .map((w) => (w.length > 4 && w.endsWith('s') && !w.endsWith('ss') ? w.slice(0, -1) : w)))];
}

function mdFiles(dir, limit = 600) {
  const out = [];
  (function rec(d, depth) {
    if (out.length >= limit || depth > 4) return;
    let ents = [];
    try { ents = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of ents) {
      if (e.name.startsWith('.')) continue;
      const p = path.join(d, e.name);
      if (e.isDirectory()) rec(p, depth + 1);
      else if (e.name.endsWith('.md')) out.push(p);
    }
  })(dir, 0);
  return out;
}

export function nowBlock(raw) {
  return (/^## Now\s*\n([\s\S]*?)(?=^---\s*$|^## )/m.exec(toLf(raw))?.[1] || '')
    .split('\n').filter((l) => !/^\*[^*].*\*$/.test(l.trim())).join('\n').trim();
}

// Index lookup plus grep. Returns { notes: [{name, path, now, snippet, score}], decisions: [line] }.
export function retrieve(vault, query, { max = 4, folders = ['01_Projects', '02_Areas', '03_Resources'] } = {}) {
  const toks = queryTokens(query);
  const res = { notes: [], decisions: [], tokens: toks };
  if (!vault || !toks.length) return res;
  const hits = (s) => toks.reduce((n, t) => n + (s.includes(t) ? 1 : 0), 0);
  const scores = new Map();
  const bump = (name, s) => scores.set(name, (scores.get(name) || 0) + s);

  let index = '';
  try { index = fs.readFileSync(path.join(vault, '_INDEX.md'), 'utf8'); } catch {}
  for (const line of index.split('\n')) {
    const names = [...line.matchAll(/\[\[([^\]|#]+)/g)].map((m) => m[1].trim());
    if (!names.length) continue;
    const h = hits(line.toLowerCase());
    if (h) bump(names[0], h * 2);
  }
  const byName = new Map();
  for (const f of folders.flatMap((d) => mdFiles(path.join(vault, d)))) {
    const name = path.basename(f, '.md');
    byName.set(name, f);
    let raw = '';
    try { raw = fs.readFileSync(f, 'utf8').toLowerCase(); } catch { continue; }
    const inName = hits(name.toLowerCase().replace(/[-_]/g, ' '));
    const inBody = toks.reduce((n, t) => n + Math.min(5, raw.split(t).length - 1), 0);
    if (inName || inBody) bump(name, inName * 3 + inBody * 0.25);
  }
  const ranked = [...scores].filter(([n]) => byName.has(n)).sort((a, b) => b[1] - a[1]).slice(0, max);
  const top = ranked[0]?.[1] || 0;
  for (const [name, score] of ranked) {
    if (score < Math.max(1.5, top * 0.25)) continue;
    const file = byName.get(name);
    const raw = toLf(fs.readFileSync(file, 'utf8'));
    const body = raw.replace(/^---\n[\s\S]*?\n---\n/, '');
    res.notes.push({ name, path: path.relative(vault, file), now: nowBlock(raw), snippet: body.slice(0, 700).trim(), score: +score.toFixed(2) });
  }
  let decisions = '';
  try { decisions = fs.readFileSync(path.join(vault, '_System', 'decisions.md'), 'utf8'); } catch {}
  res.decisions = decisions.split('\n').filter((l) => /^- \*\*\d{4}-/.test(l))
    .map((l) => [l, hits(l.toLowerCase())]).filter(([, h]) => h)
    .sort((a, b) => b[1] - a[1] || b[0].slice(4, 14).localeCompare(a[0].slice(4, 14)))
    .slice(0, 5).map(([l]) => l);
  return res;
}

// What a tool-using agent gets with this message: pointers, not the vault.
export function contextNote(r, { full = false } = {}) {
  if (!r.notes.length && !r.decisions.length) return '';
  const lines = ['[FRIDAY: vault notes relevant to this message. Read only what you need; cite as [[name]].]'];
  for (const n of r.notes) {
    lines.push(`- [[${n.name}]] (${n.path})`);
    if (full && n.now) lines.push(n.now.split('\n').map((l) => '  ' + l).join('\n').slice(0, 1200));
  }
  if (r.decisions.length) {
    lines.push('Matching lines from [[decisions]] (_System/decisions.md):');
    for (const d of r.decisions) lines.push('  ' + d.slice(0, 400));
  }
  return lines.join('\n') + '\n[end vault context]\n\n';
}

// Everything Ollama sees about the vault: rules, critical facts, retrieved notes.
export function ollamaSystem(vault, query, { max = 4, budget = 12000 } = {}) {
  let ops = '';
  try { ops = fs.readFileSync(OPS_FILE, 'utf8').replaceAll("{{user's}}", userPossessive()).replaceAll('{{user}}', userName()); } catch {}
  // The protocol's intro, then the ops: Ollama reads what FRIDAY retrieves for it below.
  const parts = [renderProtocol(vault).replace(/## Reading[\s\S]*$/, '').trim(), ops.trim()];
  try { parts.push('## Critical facts\n' + toLf(fs.readFileSync(path.join(vault, '_System', 'CRITICAL_FACTS.md'), 'utf8')).replace(/^---\n[\s\S]*?\n---\n/, '').slice(0, 3000)); } catch {}
  const r = retrieve(vault, query, { max });
  for (const n of r.notes) parts.push(`## [[${n.name}]] (${n.path})\n${(n.now || n.snippet).slice(0, 2000)}`);
  if (r.decisions.length) parts.push('## Matching decisions ([[decisions]])\n' + r.decisions.join('\n'));
  let out = parts.join('\n\n');
  if (out.length > budget) out = out.slice(0, budget) + '\n[truncated]';
  return { system: out, retrieved: r };
}

// ---- proposed writes ---------------------------------------------------------
const OPS = new Set(['log', 'decision', 'now', 'create', 'append']);

export function parseProposals(text) {
  const ops = [];
  const errors = [];
  for (const m of (text || '').matchAll(/```friday-vault[^\n]*\n([\s\S]*?)```/g)) {
    try {
      const v = JSON.parse(m[1]);
      for (const op of [].concat(v)) {
        if (op && OPS.has(op.op)) ops.push(op);
        else errors.push(`unknown op ${JSON.stringify(op?.op)}`);
      }
    } catch (e) { errors.push(`bad JSON: ${e.message}`); }
  }
  return { ops, errors };
}

const CREATE_DIRS = ['01_Projects/', '02_Areas/', '03_Resources/', '_System/Sessions/'];
const INDEX_SECTION = { '01_Projects/': '## Projects', '02_Areas/': '## Areas', '03_Resources/': '## Resources' };

function localDate(d) {
  const p = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

function resolveIn(vault, rel) {
  if (typeof rel !== 'string' || !rel.trim()) throw new Error('missing path');
  const norm = path.posix.normalize(rel.replace(/\\/g, '/').replace(/^\.\//, ''));
  if (path.isAbsolute(rel) || norm.startsWith('..')) throw new Error(`path outside the vault: ${rel}`);
  if (/^(00_Raw|\.git|\.obsidian)(\/|$)/i.test(norm)) throw new Error(`${norm.split('/')[0]} is read-only`);
  return { norm, abs: path.join(vault, norm) };
}

const oneLine = (s) => String(s || '').replace(/\s+/g, ' ').trim();

// Read a note as LF text, change it, write it back with its own line endings.
// A missing file is '' (and new files are LF).
function editFile(abs, fn, { must = true } = {}) {
  let raw = '';
  try { raw = fs.readFileSync(abs, 'utf8'); } catch (e) { if (must) throw e; }
  const next = fn(toLf(raw));
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, withEol(next, raw ? eolOf(raw) : '\n'));
}

// Applies one op to the files (no git). Returns the vault-relative paths changed.
export function applyOp(vault, op, { date = new Date() } = {}) {
  const day = localDate(date);
  switch (op.op) {
    case 'log': {
      const kind = oneLine(op.kind || 'note').split(' ')[0].toLowerCase();
      if (!op.title) throw new Error('log needs a title');
      editFile(path.join(vault, '_System', 'log.md'), (raw) => {
        const sep = raw && !raw.endsWith('\n') ? '\n' : '';
        return `${raw}${sep}\n## [${day}] ${kind} | ${oneLine(op.title)}\n${String(op.body || '').trim()}\n`;
      }, { must: false });
      return ['_System/log.md'];
    }
    case 'decision': {
      if (!op.quote) throw new Error(`decision needs ${userPossessive()} exact words (quote)`);
      const note = oneLine(op.note || 'project-friday').replace(/^\[\[|\]\]$/g, '');
      const summary = oneLine(op.summary || 'Decision').replace(/\.$/, '');
      const line = `- **${day}** · [[${note}]] · **${summary}.** *"${String(op.quote).replace(/\s+/g, ' ').trim()}"*`;
      editFile(path.join(vault, '_System', 'decisions.md'), (raw) => {
        const lines = raw.split('\n');
        const at = lines.findIndex((l) => /^- \*\*\d{4}-/.test(l));
        if (at >= 0) lines.splice(at, 0, line); else lines.push(line);
        return lines.join('\n');
      });
      return ['_System/decisions.md'];
    }
    case 'now': {
      const { norm, abs } = resolveIn(vault, op.path);
      editFile(abs, (raw) => {
        const m = /^## Now[ \t]*\n[\s\S]*?(?=^---\s*$|^## |(?![\s\S]))/m.exec(raw);
        if (!m) throw new Error(`${norm} has no ## Now block`);
        const block = `## Now\n*Rewritten in place, never appended. Updated ${day}.*\n${String(op.body || '').trim()}\n\n`;
        const next = raw.slice(0, m.index) + block + raw.slice(m.index + m[0].length);
        return next.replace(/^(---\n[\s\S]*?^updated:\s*)\S+/m, `$1${day}`);
      });
      return [norm];
    }
    case 'create': {
      const { norm, abs } = resolveIn(vault, op.path);
      if (!CREATE_DIRS.some((d) => norm.startsWith(d))) throw new Error(`new notes go under ${CREATE_DIRS.join(', ')}`);
      if (!norm.endsWith('.md')) throw new Error('notes are .md files');
      if (fs.existsSync(abs)) throw new Error(`${norm} already exists`);
      fs.mkdirSync(path.dirname(abs), { recursive: true });
      fs.writeFileSync(abs, String(op.content || '').replace(/\n*$/, '\n'));
      const changed = [norm];
      const section = Object.entries(INDEX_SECTION).find(([d]) => norm.startsWith(d))?.[1];
      if (section) {
        const name = path.basename(norm, '.md');
        const entry = /^- \[\[/.test(op.index || '') ? oneLine(op.index) : `- [[${name}]]: ${oneLine(op.index || 'new note')}`;
        editFile(path.join(vault, '_INDEX.md'), (idx) => {
          const lines = idx.split('\n');
          const start = lines.findIndex((l) => l.startsWith(section));
          if (start < 0) lines.push('', entry);
          else {
            let end = lines.findIndex((l, i) => i > start && /^## /.test(l));
            if (end < 0) end = lines.length;
            while (end > start + 1 && !lines[end - 1].trim()) end--;
            lines.splice(end, 0, entry);
          }
          return lines.join('\n');
        }, { must: false });
        changed.push('_INDEX.md');
      }
      return changed;
    }
    case 'append': {
      const { norm, abs } = resolveIn(vault, op.path);
      if (norm.startsWith('_System/')) throw new Error('_System notes change only through log and decision');
      if (!fs.existsSync(abs)) throw new Error(`${norm} does not exist (use create)`);
      editFile(abs, (raw) => `${raw}${raw.endsWith('\n') ? '' : '\n'}\n${String(op.content || '').trim()}\n`);
      return [norm];
    }
    default: throw new Error(`unknown op ${op.op}`);
  }
}

// Files in the vault with uncommitted changes (tracked or new), vault-relative with
// forward slashes. Async, so a turn can take it at its start without waiting. A vault
// that is not a git repo gives null.
export function vaultStatus(vault) {
  return new Promise((resolve) => {
    execFile('git', ['-C', vault, 'status', '--porcelain=v1', '-z', '-uall'], { encoding: 'utf8', timeout: 20000, maxBuffer: 16 << 20 }, (err, out) => {
      if (err) return resolve(null);
      const set = new Set();
      const parts = out.split('\0');
      for (let i = 0; i < parts.length; i++) {
        const e = parts[i];
        if (!e) continue;
        set.add(e.slice(3));
        if (/^R|^C/.test(e)) i++; // a rename carries its old path next
      }
      resolve(set);
    });
  });
}

function git(vault, args, timeout = 60000) {
  return execFileSync('git', ['-C', vault, ...args], { encoding: 'utf8', timeout, stdio: ['ignore', 'pipe', 'pipe'] });
}
const gitErr = (e) => String(e.stderr || e.message).trim().split('\n').slice(-2).join(' ');

// One writer for the vault. submit() may be called from any number of agents at
// once; batches run strictly one after another.
export function createVaultQueue({ vault, sync = true, now = () => new Date() }) {
  let chain = Promise.resolve();
  let pending = 0;
  async function run(ops, { source = 'friday', message } = {}) {
    const report = { results: [], committed: false, pushed: false, warnings: [] };
    const isRepo = fs.existsSync(path.join(vault, '.git'));
    const hasRemote = isRepo && (() => { try { return !!git(vault, ['remote']).trim(); } catch { return false; } })();
    // Uncommitted edits of the user's: a pull would stash and re-apply them (conflict
    // markers in his notes if the remote changed the same files), and committing a file
    // FRIDAY also touched would commit his unfinished edits. Write the note only.
    const dirty = isRepo && (() => { try { return !!git(vault, ['status', '--porcelain', '--untracked-files=no']).trim(); } catch { return false; } })();
    if (dirty) {
      for (const op of ops) {
        try { applyOp(vault, op, { date: now() }); report.results.push({ op: op.op, ok: true, path: op.path || null }); } catch (e) { report.results.push({ op: op.op, ok: false, path: op.path || null, error: e.message }); }
      }
      report.warnings.push('the vault has uncommitted changes, so this was written but not pulled, committed or pushed; your next sync includes it');
      return report;
    }
    if (sync && hasRemote) {
      try { git(vault, ['pull', '--rebase', '--autostash', '-q']); } catch (e) { report.warnings.push(`pull failed: ${gitErr(e)}`); }
    }
    const changed = new Set();
    for (const op of ops) {
      try {
        for (const p of applyOp(vault, op, { date: now() })) changed.add(p);
        report.results.push({ op: op.op, ok: true, path: op.path || null });
      } catch (e) { report.results.push({ op: op.op, ok: false, path: op.path || null, error: e.message }); }
    }
    if (!isRepo || !changed.size) return report;
    commitPush([...changed], message || `FRIDAY (${source}): ${ops.map((o) => o.op).join(', ')}`, report, { hasRemote, pullOk: true });
    return report;
  }
  // Commit exactly `paths`, then push. `pullOk`: nothing else is uncommitted, so a pull
  // before a retried push cannot touch the user's edits.
  function commitPush(paths, msg, report, { hasRemote, pullOk }) {
    try {
      git(vault, ['add', '-A', '--', ...paths]);
      try { git(vault, ['commit', '-q', '-m', msg, '--', ...paths]); } catch (e) {
        // No git identity configured (e.g. a bare environment): commit as FRIDAY rather than leave it uncommitted.
        if (!/identity|email address|user\.name/i.test(gitErr(e))) throw e;
        git(vault, ['-c', 'user.name=FRIDAY', '-c', 'user.email=friday@localhost', 'commit', '-q', '-m', msg, '--', ...paths]);
      }
      report.committed = true;
    } catch (e) { report.warnings.push(`commit failed: ${gitErr(e)}`); return; }
    if (sync && hasRemote) {
      try { git(vault, ['push', '-q']); report.pushed = true; } catch {
        if (!pullOk) { report.warnings.push('committed, not pushed: the remote is ahead and your uncommitted edits stop a pull; your next sync pushes it'); return; }
        try { git(vault, ['pull', '--rebase', '--autostash', '-q']); git(vault, ['push', '-q']); report.pushed = true; }
        catch (e) { report.warnings.push(`push failed: ${gitErr(e)}`); }
      }
    }
  }
  // An agent's own edits (it writes the vault directly): commit those files and push.
  // The caller passes only files that had none of the user's uncommitted edits before the
  // turn, so committing them never takes his unfinished work along.
  async function commitEdits(paths, { source = 'agent' } = {}) {
    const report = { results: [], committed: false, pushed: false, warnings: [], paths };
    if (!paths.length || !fs.existsSync(path.join(vault, '.git'))) return report;
    const hasRemote = (() => { try { return !!git(vault, ['remote']).trim(); } catch { return false; } })();
    const name = (p) => path.posix.basename(p, '.md');
    const msg = `FRIDAY (${source}): ${paths.length <= 3 ? paths.map(name).join(', ') : `${paths.length} notes`}`;
    // Other tracked files with uncommitted changes are the user's: then never pull.
    const mine = new Set(paths);
    let others = true;
    try { others = git(vault, ['status', '--porcelain', '--untracked-files=no']).split('\n').filter(Boolean).some((l) => !mine.has(l.slice(3))); } catch {}
    commitPush(paths, msg, report, { hasRemote, pullOk: !others });
    return report;
  }
  const enqueue = (fn) => {
    pending++;
    const job = chain.then(fn).finally(() => { pending--; });
    chain = job.catch(() => {});
    return job;
  };
  return {
    submit(ops, opts) { return enqueue(() => run(ops, opts)); },
    commitEdits(paths, opts) { return enqueue(() => commitEdits(paths, opts)); },
    get pending() { return pending; },
    idle() { return chain; },
  };
}
